"""Complete v1 catalog emitter, executed by GenerateDesignBaseline.py.

Every delivered item, facility, recipe, technology, technology sale and region is
emitted. Legacy enum ordinals stay first so older saves keep their meaning; new
items are appended in delivery order.
"""


def build_catalog(data, mapping, runtime_items, number):
    legacy_enum = list(mapping.keys())
    reverse = {v: k for k, v in mapping.items()}

    def pascal(key):
        return ''.join(part[:1].upper() + part[1:] for part in key.split('_'))

    item_keys = [mapping[e] for e in legacy_enum] + [k for k in data['items'] if k not in reverse]
    enum_names = legacy_enum + [pascal(k) for k in item_keys[len(legacy_enum):]]
    assert len(set(enum_names)) == len(enum_names)
    enum_of = dict(zip(item_keys, enum_names))

    def s(value):
        return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"') + '"'

    def d(value):
        return repr(float(value)) if value is not None else '0'

    def amounts(table):
        return 'new ItemQuantity[]{' + ','.join(f'new ItemQuantity(ItemId.{enum_of[k]},{d(v)})' for k, v in (table or {}).items()) + '}'

    def strings(values):
        return 'new string[]{' + ','.join(s(v) for v in values) + '}'

    rows = [runtime_items[k] for k in item_keys]
    out = ['// Generated by Tools/GenerateDesignBaseline.py from the October 11 v1 delivery. Do not edit by hand.',
           'namespace CrazyRubbish.Core', '{',
           '    public enum ItemId', '    {', '        ' + ', '.join(enum_names), '    }',
           '    public static partial class DesignCatalog', '    {']
    out.append('        public static readonly string[] ItemKeys={' + ','.join(s(k) for k in item_keys) + '};')
    out.append('        public static readonly string[] ItemNames={' + ','.join(s(r.get('name', k)) for r, k in zip(rows, item_keys)) + '};')
    out.append('        public static readonly string[] ItemCategories={' + ','.join(s(r.get('category', '废旧设备')) for r in rows) + '};')
    out.append('        public static readonly string[] ItemMarketGroups={' + ','.join(s(r.get('market_group') or k) for r, k in zip(rows, item_keys)) + '};')
    out.append('        public static readonly int[] ItemTicks={' + ','.join(str(round(r['capacity'] * 20)) for r in rows) + '};')
    out.append('        public static readonly bool[] ItemBuyable={' + ','.join('true' if r.get('buy') is not None and not r.get('provenance') else 'false' for r in rows) + '};')
    for field, name in [('buy', 'ItemBuy'), ('sell_base', 'ItemSale'), ('sell_floor', 'ItemFloor')]:
        out.append(f'        public static readonly decimal[] {name}={{' + ','.join(number(r.get(field)) + 'm' for r in rows) + '};')
    out.append('        public static readonly string[] ToolFamilies={' + ','.join(s(r.get('tool_family') or '') for r in rows) + '};')
    out.append('        public static readonly int[] ToolDurability={' + ','.join(str(r.get('durability') or 300) for r in rows) + '};')
    out.append('        public static readonly double[] ToolEfficiency={' + ','.join(d(r.get('efficiency') or 1) for r in rows) + '};')
    out.append('        public static readonly int[] PackDisposalTicks={' + ','.join(str(round((r.get('disposal_capacity') or 0) * 20)) for r in rows) + '};')
    out.append('        public static readonly ItemQuantity[][] PackPayloads={' + ','.join(amounts(r.get('payload')) if r.get('payload') else 'null' for r in rows) + '};')

    out.append('        public static readonly FacilityDef[] Facilities={')
    skip = ('builders', 'operators', 'maintainers', 'power', 'durability', 'ports', 'buffers_batches_in', 'buffers_batches_out',
            'build_purchase_equivalent', 'sell_at_full_durability')
    for i, (k, f) in enumerate(data['facilities'].items()):
        w, h = f['size']
        extra = {x: y for x, y in f.items() if isinstance(y, (int, float)) and not isinstance(y, bool) and x not in skip}
        out.append(f'            new FacilityDef({i},{s(k)},{s(f["name"])},{w},{h},{amounts(f.get("build"))},{f.get("operators", 0)},{f.get("maintainers", 0)},'
                   f'{d(f.get("power", 0))},{d(f.get("durability") or 0)},{f.get("ports", 0)},{f.get("buffers_batches_in", 2)},{f.get("buffers_batches_out", 2)},'
                   f'{s(f.get("technology", ""))},{d(extra.get("capacity", 0))},{d(extra.get("beds", 0))},{d(extra.get("radius", 0))},'
                   f'{d(extra.get("output_power", 0))},{d(extra.get("heat_output", 0))},{int(f.get("region_required", 1))}),')
    out.append('        };')

    out.append('        public static readonly RecipeDef[] Recipes={')
    flag_names = ('preserve_payload', 'requires_grow_lamp', 'one_time_per_vein', 'infinite_source', 'unique_vehicle_on_platform',
                  'requires_tested_vehicle', 'binding_strap_becomes_damaged_pet', 'preserve_unique_vehicle', 'requires_unrecognized_composition')
    for i, (k, r) in enumerate(data['recipes'].items()):
        flags = [flag for flag in flag_names if r.get(flag)]
        tools = 'new ToolNeed[0]' if not r.get('tools') else 'new ToolNeed[]{' + ','.join(f'new ToolNeed({s(t)},{n})' for t, n in r['tools'].items()) + '}'
        stages = 'null' if not r.get('stages') else 'new RecipeStage[]{' + ','.join(f'new RecipeStage({s(st["kind"])},{d(st["seconds"])})' for st in r['stages']) + '}'
        effluent = r.get('optional_effluent_capture') or {}
        out.append(f'            new RecipeDef({i},{s(k)},{s(r["name"])},{s(r["facility"])},{amounts(r["inputs"])},{amounts(r["outputs"])},'
                   f'{d(r["human_seconds"])},{d(r["machine_seconds"])},{d(r["natural_seconds"])},{d(r["power"])},{tools},{strings(r.get("technologies", []))},'
                   f'{int(r.get("region_required", 1))},{s(r.get("requires_state", ""))},{s(r.get("vein", ""))},{strings(flags)},'
                   f'{amounts(r.get("addons"))},{stages},{amounts(effluent.get("addon"))},{d(effluent.get("yield_water_fraction", 0))},'
                   f'{s(r.get("cancel_package", ""))},{amounts(r.get("composition_region2")) if r.get("composition_region2") else "null"}),')
    out.append('        };')

    out.append('        public static readonly TechnologyDef[] Technologies={')
    for i, (k, t) in enumerate(data['technologies'].items()):
        all_items = 'new ItemId[]{' + ','.join('ItemId.' + enum_of[x] for x in t['acquired_all']) + '}'
        any_items = 'new ItemId[]{' + ','.join('ItemId.' + enum_of[x] for x in t['acquired_any']) + '}'
        out.append(f'            new TechnologyDef({i},{s(k)},{s(t["name"])},{all_items},{any_items},{strings(t["parents"])},{strings(t["facilities"])},'
                   f'{int(t.get("region_required", 1))},{s(t.get("notes", ""))}),')
    out.append('        };')

    out.append('        public static readonly TechnologySaleDef[] TechnologySales={')
    for i, (k, t) in enumerate(data['technology_sales'].items()):
        items = 'new ItemId[]{' + ','.join('ItemId.' + enum_of[x] for x in t['items']) + '}'
        out.append(f'            new TechnologySaleDef({i},{s(k)},{s(t["name"])},{number(t["cash"])}m,{items},{strings(t["requires_technologies"])}),')
    out.append('        };')

    out.append('        public static readonly RegionDef[] Regions={')
    for k, r in data['regions'].items():
        lx0, ly0, lx1, ly1 = r['land_rectangle']
        gx0, gy0, gx1, gy1 = r['garbage_rectangle']
        veins = ','.join(f'new VeinDef({s(v)},{a["rectangle"][0]},{a["rectangle"][1]},{a["rectangle"][2]},{a["rectangle"][3]})' for v, a in r.get('veins', {}).items())
        out.append(f'            new RegionDef({k},{s(r["name"])},{number(r["purchase_cash"])}m,{lx0},{ly0},{lx1},{ly1},{gx0},{gy0},{gx1},{gy1},'
                   f'{amounts(r.get("fixed_items"))},new VeinDef[]{{{veins}}}),')
    out.append('        };')
    out += ['    }', '}', '']
    return '\n'.join(out).encode('utf-8'), len(item_keys)
