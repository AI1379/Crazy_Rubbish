"""Generate the implemented runtime slice from the immutable October 11 delivery.

Run again after an intentional baseline change; --check verifies checked-in output.
The full JSON is retained for subsequent production-line work, not advertised as implemented.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Docs/Source/ArtDelivery_2026-10-13/数值配置/全局数值_v1.json'
data = json.loads(SOURCE.read_text(encoding='utf-8-sig'))
mapping = dict(zip('WasteWood MixedPlastic RecoveredFastener WoodHandSaw Plank WoodHandle WoodChips SteelPart CopperPart RecoveredWire ThermalModule GeneratorModule Screwdriver Wrench Hammer Scissors SewingKit Food DrinkingWater Soap WasteTextile OldClothes DamagedMotor SteelMaterial CopperMaterial PowerAsh Motor MachineBlade HeatingElement Container HandleMould BoxMould FeedingModule GrowingLight FurnaceModule FurnaceLining Fixture AluminumPart AluminumMaterial ToolSteelWaste OldCutter OldWasher OldFormer MouldBox OldContainer WireBundle OldGrowingLamp OldFeeder OldFurnace OldMetalTable OldControlBox LightingModule OldLamp SawBlade HammerHead ScrewdriverRod BroomHead SortedWood BrokenWoodTool'.split(),
    'waste_wood plastic_mix fasteners handsaw_wood boards wood_handle wood_chips steel_parts copper_parts wire thermal_module generator_module screwdriver_wood wrench hammer_wood scissors sewing food water soap waste_textile old_clothes old_motor steel_scrap copper_scrap ash motor machine_saw heater container handle_mold box_mold feeder grow_light_module furnace_module lining fixture aluminum_parts aluminum_scrap tool_steel_scrap old_cutter old_washer old_former old_molds old_container old_wires old_grow_light old_feeder old_furnace old_fixture old_control_basic light_module old_lamp handsaw_blade hammer_head screwdriver_shaft broom_head sorted_wood broken_handsaw_wood'.split()))
assert len(mapping) == 59
# These two S5 objects disappeared from v1. Preserve old saves and the confirmed
# gradual opening without pretending that they are new v1 catalog entries.
runtime_items = dict(data['items'])
runtime_items.update({
    'old_container': {'capacity': 2, 'buy': None, 'sell_base': None, 'sell_floor': None},
    'old_lamp': {'capacity': 6, 'buy': None, 'sell_base': None, 'sell_floor': None},
})
assert all(key in runtime_items for key in mapping.values())
reverse = {v: k for k, v in mapping.items()}
def number(value):
    return str(value if value is not None else 0).lower()
lines = ['// Generated by Tools/GenerateDesignBaseline.py. Do not edit by hand.',
         'using System;', 'namespace CrazyRubbish.Core', '{',
         '    public static class DesignBaseline', '    {',
         f'        public const string Version = "{data["version"]}";',
         f'        public const string SourceSha256 = "{hashlib.sha256(SOURCE.read_bytes()).hexdigest()}";',
         f'        public const int RegisteredItems = {len(data["items"])}, RegisteredFacilities = {len(data["facilities"])}, RegisteredRecipes = {len(data["recipes"])}, RegisteredTechnologies = {len(data["technologies"])};',
         '        public static string StableItemId(ItemId item)', '        {', '            switch(item)', '            {']
for enum, key in mapping.items():
    lines.append(f'                case ItemId.{enum}: return "{key}";')
lines += ['                default: throw new ArgumentOutOfRangeException(nameof(item));', '            }', '        }',
          '        public static int CapacityTicks(ItemId item)', '        {', '            switch(item)', '            {']
for enum, key in mapping.items():
    lines.append(f'                case ItemId.{enum}: return {round(runtime_items[key]["capacity"] * 20)};')
lines += ['                default: throw new ArgumentOutOfRangeException(nameof(item));', '            }', '        }',
          '        public static (decimal buy, decimal sale, decimal minimum) Price(ItemId item)', '        {', '            switch(item)', '            {']
for enum, key in mapping.items():
    item = runtime_items[key]
    lines.append(f'                case ItemId.{enum}: return ({number(item.get("buy"))}m, {number(item.get("sell_base"))}m, {number(item.get("sell_floor"))}m);')
lines += ['                default: throw new ArgumentOutOfRangeException(nameof(item));', '            }', '        }',
          '        public static ItemAmount[] BuildCost(int kind)', '        {', '            switch(kind)', '            {']
facility_mapping = {1: 'wood', 2: 'disassembly', 4: 'bench', 8: 'generator', 16: 'housing', 32: 'streetlamp', 64: 'electric_wood', 128: 'auto_wood'}
for kind, key in facility_mapping.items():
    cost = ', '.join(f'new ItemAmount(ItemId.{reverse[item]}, {amount})' for item, amount in data['facilities'][key]['build'].items())
    lines.append(f'                case {kind}: return new[] {{ {cost} }};')
lines += ['                default: throw new ArgumentOutOfRangeException(nameof(kind));', '            }', '        }']
lines += ['        public static int PortLimit(int kind)', '        {', '            switch(kind)', '            {', '                case -1: return 8;']
for kind, key in facility_mapping.items():
    lines.append(f'                case {kind}: return {data["facilities"][key]["ports"]};')
lines += ['                default: return 0;', '            }', '        }']
constants = {
    'ElectricHumanSeconds': data['recipes']['electric_boards']['human_seconds'],
    'WoodMachineSeconds': data['recipes']['electric_boards']['machine_seconds'],
    'ElectricWoodLoad': data['facilities']['electric_wood']['power'],
    'AutomaticWoodLoad': data['facilities']['auto_wood']['power'],
    'MachineMaximum': data['global']['maintenance']['maximum'],
    'MachineDecay': data['global']['maintenance']['active_decay_per_second'],
    'MachineRepair': data['global']['maintenance']['repair_per_second_at_efficiency1'],
    'MachineRestart': data['global']['maintenance']['restart_at'],
    'BeltSpeed': data['global']['storage']['belt_entities_per_second'],
    'BeltLoad': data['global']['storage']['belt_power_per_cell'],
}
for name, value in constants.items():
    lines.append(f'        public const double {name} = {number(value)};')
for section, key, name in [('power','generator_power','GeneratorPower'), ('power','housing_valid_ratio','HousingValidRatio'), ('power','lamp_valid_ratio','LampValidRatio')]:
    lines.append(f'        public const double {name} = {number(data["global"][section][key])};')
lines += ['    }', '}', '']
outputs = {
    ROOT/'Assets/_Game/Scripts/Core/DesignBaseline.cs': '\n'.join(lines).encode('utf-8'),
    ROOT/'Assets/_Game/Resources/Design/Balance20261011.json': SOURCE.read_bytes(),
}
for path, content in outputs.items():
    if '--check' in sys.argv:
        assert path.is_file() and path.read_bytes() == content, f'Stale generated baseline: {path}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
print(f'{data["version"]}: {len(mapping)} runtime item mappings; complete delivery catalog preserved; outputs verified.')
